'use strict';
// Converts the long-format rating CSV into rating rows.
// CSV columns: table,source_page,size,ratio,quantity,unit,value
// Each rating group is four consecutive lines: output_rpm, input_rpm, power_kw, torque_nm.
const fs = require('node:fs');

const QUANTITIES = ['output_rpm', 'input_rpm', 'power_kw', 'torque_nm'];
const RATING_TABLES = new Set(['rating_single_stage', 'rating_double_stage']);
const NUMBER = /^\d+(\.\d+)?$/;

function splitLine(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (c === '"') quoted = false;
      else cur += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { out.push(cur); cur = ''; }
    else cur += c;
  }
  out.push(cur);
  return out;
}

function importRating(csvText) {
  const lines = csvText.split(/\r?\n/);
  const recs = [];
  for (let i = 1; i < lines.length; i++) {
    if (lines[i].trim() === '') continue;
    const lineNo = i + 1;
    const f = splitLine(lines[i]);
    if (f.length !== 7) throw new Error(`line ${lineNo}: expected 7 columns, got ${f.length}`);
    if (!RATING_TABLES.has(f[0])) continue;
    recs.push({ lineNo, size: f[2], ratio: f[3], quantity: f[4], raw: f[6] });
  }

  const rows = [];
  const seen = new Set();
  for (let i = 0; i < recs.length; i += 4) {
    const group = recs.slice(i, i + 4);
    const first = group[0];
    if (group.length < 4) {
      throw new Error(`line ${first.lineNo}: incomplete rating group (${group.length} of 4 lines)`);
    }
    const v = {};
    group.forEach((r, k) => {
      if (r.quantity !== QUANTITIES[k]) {
        throw new Error(`line ${r.lineNo}: expected ${QUANTITIES[k]}, found ${r.quantity}`);
      }
      if (r.size !== first.size || r.ratio !== first.ratio) {
        throw new Error(`line ${r.lineNo}: size/ratio ${r.size}/${r.ratio} differs from group start ${first.size}/${first.ratio}`);
      }
      if (!NUMBER.test(r.raw)) throw new Error(`line ${r.lineNo}: invalid number "${r.raw}" for ${r.quantity}`);
      const n = Number(r.raw);
      if (!Number.isFinite(n)) throw new Error(`line ${r.lineNo}: non-finite value "${r.raw}"`);
      v[r.quantity] = n;
    });
    const id = `RP${first.size}-${first.ratio}-${v.output_rpm}`;
    if (seen.has(id)) throw new Error(`line ${first.lineNo}: duplicate row id ${id}`);
    seen.add(id);
    rows.push({
      id,
      model: `RP ${first.size}`,
      size: first.size,
      ratio: first.ratio,
      n2: v.output_rpm,
      n1: v.input_rpm,
      kw: v.power_kw,
      torque: v.torque_nm,
    });
  }
  return rows;
}

module.exports = { importRating };

if (require.main === module) {
  const [, , inPath, outPath] = process.argv;
  if (!inPath || !outPath) {
    console.error('usage: node import-spec-table.js <csv> <out.js>');
    process.exit(1);
  }
  const rows = importRating(fs.readFileSync(inPath, 'utf8'));
  const body = rows.map((r) => '  ' + JSON.stringify(r)).join(',\n');
  fs.writeFileSync(outPath, `'use strict';\n// Generated by import-spec-table.js from the OCR RP rating CSV. Do not edit by hand.\nmodule.exports = [\n${body}\n];\n`);
  console.log(`${rows.length} rows`);
}
